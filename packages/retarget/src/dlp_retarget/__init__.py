"""사람 손 3D → 로봇 관절 궤적 (리타기팅, ADR 0047·0068).

고객이 준 로봇 설계(URDF)에 사람 1인칭 손 동작(세션 월드 좌표 손목·손가락 끝, ADR 0046)을 옮겨
로봇 관절 각 궤적과 프레임별 도달 가능성을 낸다. 내보내기(`dlp export lerobot --robot <ID>`,
`dlp_export.robot`)가 부른다. 영상은 바꾸지 않는다.

로봇은 두 가지다 (로봇 설정이 정한다, 어느 쪽이든 팔 하나가 사람 손 하나를 따라간다).
- 평행 그리퍼 로봇 (ADR 0047·0053): 손목·엄지 끝·검지 끝에서 끝단 목표(위치·접근 축·닫힘 축)를
  만들어 팔 관절을 풀고, 엄지-검지 거리를 그리퍼 관절 하나로 옮긴다.
- 다지 손 로봇 (ADR 0068): 손목과 대응한 손가락 끝(1~5개)의 위치를 팔 관절 + 손가락 관절로 함께
  푼다. 방향 목표는 없다.

모듈:
- `urdf`: URDF 관절만 읽는 직렬 연쇄(`Chain`)와 나무(`Tree`, 끝 링크 여러 개)의 정기구학·야코비안.
- `robot`: 로봇 등록(`config/robots/<ID>.yaml`), 모델 파일 sha256 확인, 손 → 로봇 배치, 그리퍼
  설정 또는 다지 손 설정(손가락 대응·손 배율·허용 오차)과 그 구조 검사.
- `policy`: 리타기팅 정책(`config/policies/retarget.yaml`).
- `targets`: 손 점 → 끝단 목표와 그리퍼 열림(평행 그리퍼), 손목·손가락 끝 목표(다지 손).
- `ik`: 팔 IK 풀이기 인터페이스와 내장 감쇠 최소제곱 풀이기(관절·속도 한계, 매끄러움).
- `hand_ik`: 다지 손 IK(손목·손가락 끝 위치를 팔 관절과 손가락 관절로 푸는 감쇠 최소제곱).
- `mink`: 격리 환경의 mink(MuJoCo) 풀이기 어댑터 (선택, 평행 그리퍼 로봇만).
- `retarget`: 에피소드 하나를 리타기팅하고 도달 가능성 보고를 만든다 (두 로봇 종류).

지키는 규칙:
- 목표를 지어내거나 바꾸지 않는다. 손 점이 없는 프레임은 목표가 없다(`target_present=0`). 로봇이
  닿지 못한 프레임은 가장 가까운 해와 오차를 내고 `reachable=0`으로 표시한다. 작업 공간 안으로
  목표를 잘라 "도달"로 만들지 않는다. 다지 손은 손가락마다도 같다: 끝 점이 없는 손가락은 그
  관절을 유지하고 손가락별 표시로 남기며, 닿지 못한 손가락은 손가락별 오차와 표시로 드러낸다.
- 지원하지 않는 로봇 구조(mimic 관절, 손가락끼리 관절을 함께 쓰는 손 등)는 풀이를 지어내지 않고
  설정 검증에서 이유와 함께 거부한다.
- 관절 위치 한계와 속도 한계(URDF velocity x `velocity_scale` x 프레임 간격)를 모든 프레임에 지킨다.
  잘린 프레임은 `velocity_limited`로 표시한다.
- 시각은 에피소드 프레임의 마스터 타임라인 ms다. 3D 궤적(스트림 PTS 시각)에서 그 시각의 손 점을
  고르는 일은 호출자 `dlp_export.robot`이 한다 (ADR 0019).
- DB를 읽거나 쓰지 않는다. 고객 로봇 설정·모델 파일은 저장소 밖 `DLP_ROBOTS_DIR`에 두고, 모델은
  sha256을 확인한 뒤에만 읽는다.
"""
